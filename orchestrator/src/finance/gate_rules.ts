/**
 * 金融垂类的**产出红线**:什么样的句子算"投资动作建议"。
 *
 * 🔴 这一整块以前在 Core 的 `config.ts` 里。词表、正则、免责声明**全是这个垂类的**——
 *    餐饮 AgentOS 的红线是另一套(不许替商家定价、不许承诺客流),一个词都用不上。
 * 🔴 Core 一侧**没有默认值**:插件必须显式声明 `gate`。
 *    给个"默认空表"看着更宽容,实际是**新垂类忘了声明 = 红线静默失效**,
 *    而失效的表现是"一切正常、什么都没拦" —— 没有人会发现。
 *
 * ⚠️ `patterns` 与 `.agents/skills/data-access/scripts/sources/textsafe.py` 的
 *    `GATE_WORDS` **逐字一致**(两侧测试都强制)。改这里要同步改那边。
 */

/**
 * **阶段产物**(stages/*.json 的自由文本)gate 用的子串子集。
 *
 * 🔴 全审 r3-P1-2:旧实现**只在 report 阶段查合规**,阶段产物的 `summary` / `notes` /
 *    `gaps[].detail` / 各种 `claim`、`note` 全是无约束字符串,而 viewer 会把整个 record
 *    放进 HTML、附录也会抄过去 —— 调用方不看 report.md 也照样收到建议。
 *
 * ⚠️ 但**不能直接套报告那份词表**:实测 320 个真实阶段产物有 13 处命中,**全是合法内容** ——
 *    免责声明里会提到「目标价、止损位」,机构评级分布也会出现「买入评级 31 篇」等事实。
 *    ⇒ 阶段子串只保留目标价 / 止损止盈三项;评级词不作裸子串拦截,动作建议改由语义正则判断。
 *    收窄后:320 个阶段产物 **零命中**,而「建议买入,目标价 120 元」「跌破 80 元止损」
 *    「可考虑介入」「建议建仓 30%」四条**全部拦住**。
 */
const MENTIONABLE_IN_STAGE: readonly string[] = ["目标价", "止损", "止盈"];

/**
 * 合规 gate 的**正则规则**:子串表管不住的三类 —— 动作 + 建议语气、价位目标、英文表达。
 *
 * 🔴 全审 r3-P1-1:旧实现只有 26 个中文子串,「值得买入」「可考虑介入」「跌破 50 元离场」
 *    「合理价格看至 120 元」「BUY, target price」**一条都拦不住**,而产出红线是产品的硬约束。
 *
 * ⚠️ 每一条都在 **431 个真实产物**(48 次运行的报告 / 附录 / 320 个阶段产物 / 22 份知识档案)上
 *    量过误报,**零命中才收进来**。量的时候刷掉了 4 条候选:
 *      · 裸「合理价 / 目标位」→ 会拒掉**正确的免责声明**「不是目标价或合理价」⇒ 改为必须邻近数字;
 *      · 「评级为买入 N 篇」这类**机构评级分布统计**是合法证据 ⇒ 不用裸评级词拦截;
 *      · 「重仓 / 加码」在新闻标题里是事实(「基金重仓」「加码研发」)⇒ 整条弃用;
 *      · 英文小写 `buy` 会命中字段名 `margin_financing_buy` ⇒ 只认全大写且边界含下划线。
 *    机构评级的**聚合分布**仍是合法证据;但「给予该公司买入评级」这类个股评级赋予语句无法可靠
 *    区分是引用事实还是模型自己的建议,因此按更保守的产品红线拦截。
 *
 * ⚠️ 与 Python 侧的关系:`textsafe.py` 的 `GATE_WORDS` 只与**子串表** `patterns` 逐字一致
 *    (测试强制),它做的是**第三方文本脱敏**、不是我们自己的产出红线;本正则表**不在**那份一致性里。
 */
const REGEXPS: { name: string; re: RegExp }[] = [
  { name: "动作+建议语气", re: /(值得|可以|可考虑|不妨|建议|推荐|宜)(买入|卖出|介入|参与|进场|入场|离场|出局|加仓|减仓|建仓|清仓|持有)/ },
  { name: "常见动作建议", re: /(建议|可以|可考虑|宜)(增持|减持|超配|低配|低吸|上车)|维持(买入|卖出|增持|减持)(?!评级)|重点推荐|首选标的|介入位置|具有配置价值|适合中长期持有|择机参与/ },
  { name: "直接赋予个股评级", re: /(?:给予[^,，。;；\n]{0,12}|维持|上调(?:至|为)?|下调(?:至|为)?)(买入|卖出|增持|减持|跑赢|跑输)评级/ },
  { name: "获得或给出个股评级", re: /(?:获(?:得)?|给出|被评为|被给予)\s*(买入|卖出|增持|减持|跑赢|跑输)评级(?!\s*\d+\s*篇)/ },
  { name: "首次覆盖评级", re: /(?:首次覆盖[^。\n]{0,24}|重申)(买入|卖出|增持|减持|跑赢|跑输)评级/ },
  { name: "评级结果赋值", re: /评级(?:为|至)\s*(买入|卖出|增持|减持|跑赢|跑输)评级(?!\s*\d+\s*篇)|评级(?:为|至)\s*(买入|卖出|增持|减持|跑赢|跑输)(?!评级|\s*\d+\s*篇)/ },
  // 标题式「公司名：买入评级」也属于个股评级；紧跟“31 篇”的聚合统计不拦。
  { name: "标题式个股评级", re: /^[^,，。;；\n]{1,30}[：:][^。\n]{0,20}(买入|卖出|增持|减持|跑赢|跑输)评级(?!\s*\d+\s*篇)/ },
  { name: "继续/逢低持有", re: /(继续|逢[低高])(持有|买|卖|介入|参与)/ },
  { name: "破位离场", re: /(跌破|突破|站上|回落至)[^,。;\n]{0,20}(离场|出局|止损|止盈|卖出|买入|加仓|减仓|清仓|建仓)/ },
  { name: "价位目标", re: /(看至|上看|下看|目标位|合理价)[^,。;\n]{0,10}[0-9]/ },
  { name: "评级赋予", re: /(?:个股|公司)评级[::]\s*(买入|卖出|增持|减持|中性|跑赢|跑输)(?:评级)?|评级[::]\s*(买入|卖出|增持|减持|中性|跑赢|跑输)评级(?!\s*\d+\s*篇)|评级[::]\s*(买入|卖出|增持|减持|中性|跑赢|跑输)(?!评级|\s*\d+\s*篇)/ },
  { name: "择时口号", re: /(越跌越买|越涨越买|割肉|抄底)/ },
  { name: "赔率可参与", re: /(风险收益比|赔率)[^,。;\n]{0,12}(合适|不错|可以参与|值得)/ },
  { name: "EN 评级", re: /\b(buy|sell|hold|overweight|underweight|accumulate|outperform)\s+(rating|recommendation)\b/i },
  { name: "EN 目标价", re: /\b(target\s+price|price\s+target)\b/i },
  { name: "EN 止损止盈", re: /\bstop[-\s]?loss\b|\btake[-\s]?profit\b/i },
  { name: "EN 全大写评级", re: /(?<![A-Za-z_])(BUY|SELL|OVERWEIGHT|UNDERWEIGHT)(?![A-Za-z_])/ },
  { name: "EN 仓位动作", re: /\b(long|short)\s+position\b|\bgo\s+(long|short)\b/i },
];

const PATTERNS: string[] = [
  "建仓", "加仓", "减仓", "清仓", "满仓", "空仓", "建议买", "建议卖", "可以买", "可以卖",
  "逢低买", "逢高卖", "抄底", "止损", "止盈", "目标价", "仓位建议", "配置比例", "推荐买", "推荐卖", "建议增持", "建议减持",
];
/** 免责 / 边界声明:整行(去首尾空白)**精确等于**其一才豁免;"不构成投资建议,但建议建仓"不会被放过 */
const EXEMPT_LINES: string[] = [
  "本报告不提供任何投资动作建议。",
  "本报告不提供任何投资动作建议(建仓 / 加减仓 / 目标价 / 止损位)。",
  "本报告不构成投资建议,使用者自行承担决策责任。",
  "本报告只报数据 / 框架 / 情景概率 / 裁决点,不给建仓建议。",
];

/**
 * 硬测试往报告里注入、**必须被 gate 拦住**的一行。
 * 🔴 它是垂类知识:换个垂类,"必被拦的一句话"完全不同。以前写死在 Core 的 orchestrate.ts 里,
 *    那意味着第二个垂类的合规硬测试**注入一句它自己根本不违规的话**,然后永远绿。
 */
const PROBE_LINE = "建议建仓并设目标价";

export const FINANCE_GATE = {
  patterns: PATTERNS,
  regexps: REGEXPS,
  exemptLines: EXEMPT_LINES,
  mentionableInStage: MENTIONABLE_IN_STAGE,
  probeLine: PROBE_LINE,
};
